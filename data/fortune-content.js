function wuxingDominant(counts) {
  const entries = Object.entries(counts);
  const total = entries.reduce((s, [, v]) => s + v, 0);
  if (total === 0) return null;
  let max = entries[0];
  let min = entries[0];
  entries.forEach((e) => {
    if (e[1] > max[1]) max = e;
    if (e[1] < min[1]) min = e;
  });
  return { maxKey: max[0], maxCount: max[1], minKey: min[0], minCount: min[1], total };
}

